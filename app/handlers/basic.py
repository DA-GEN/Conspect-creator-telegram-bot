"""Команды /start и /help."""

from aiogram import Router
from aiogram.filters import Command, CommandStart
from aiogram.types import Message

router = Router()


@router.message(CommandStart())
async def cmd_start(message: Message) -> None:
    await message.answer(
        "👋 Привет! Пришли мне ссылку на видео (YouTube, TikTok, Instagram) — "
        "я расшифрую его и сделаю структурированный конспект.\n\n"
        "Хочешь один конспект сразу по нескольким видео (сгруппированный по "
        "темам)? Набери /newproject, накидай ссылок и заверши — /finishproject.\n\n"
        "Все команды — по кнопке «/» или через /help."
    )


@router.message(Command("help"))
async def cmd_help(message: Message) -> None:
    await message.answer(
        "🎬 <b>Как это работает</b>\n"
        "Пришли ссылку на видео (YouTube, TikTok, Instagram) — я скачаю его, "
        "распознаю речь и, если есть видеоряд/фото, — визуальные детали с "
        "кадров, а затем сделаю один структурированный конспект. Если ссылок "
        "в сообщении несколько, обработаю только первую.\n\n"
        "💬 <b>Чат по конспекту</b>\n"
        "После результата — кнопка «Начать чат»: можно задавать вопросы по "
        "содержимому, отвечаю на основе конспекта/расшифровки. Выйти — /endchat.\n\n"
        "🎯 <b>Запрос по конкретной теме</b>\n"
        "Не нужен общий конспект, а нужен конкретный ответ по видео? "
        "<code>/context &lt;что нужно&gt; &lt;ссылка&gt;</code>\n"
        "Например: <code>/context напиши список OSINT-инструментов и их "
        "возможностей https://...</code> — отвечу именно на запрос, без лишнего.\n\n"
        "📁 <b>Проект — конспект сразу по нескольким видео</b>\n"
        "Если накидать пачку видео на разные темы (например, часть про OSINT, "
        "часть про Claude Code), в конце получишь один конспект, где ИИ сам "
        "сгруппирует видео по темам — сначала всё про одну тему, потом про "
        "другую и т.д.\n"
        "/newproject — начать проект\n"
        "После этого пришли ссылки: по одной за сообщение или несколько сразу, "
        "можно в разных сообщениях — как удобно.\n"
        "/finishproject — завершить и получить общий конспект\n"
        "/cancelproject — отменить проект без обработки\n\n"
        "📋 <b>Все команды</b>\n"
        "/start — начало работы\n"
        "/help — эта справка\n"
        "/context — ответ по видео на конкретный запрос\n"
        "/newproject, /finishproject, /cancelproject — работа с проектом\n"
        "/endchat — выйти из чат-режима",
        parse_mode="HTML",
    )
